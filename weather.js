const clamp = (value, min, max) => Math.min(max, Math.max(min, value));

function seededRandom(seed) {
    let state = seed >>> 0;
    return () => {
        state += 0x6D2B79F5;
        let value = state;
        value = Math.imul(value ^ value >>> 15, value | 1);
        value ^= value + Math.imul(value ^ value >>> 7, value | 61);
        return ((value ^ value >>> 14) >>> 0) / 4294967296;
    };
}

export function buildSyntheticWeather() {
    const root = document.createElement('div');
    root.className = 'weather-app';
    root.innerHTML = '<div class="weather-sky"><header class="weather-top"><div class="weather-wordmark"><span class="weather-mark">☼</span><span><strong>Weather</strong><small>CLINGSTONE SKY MODEL</small></span></div><span class="weather-model-badge"><i></i> SYNTHETIC</span></header><main class="weather-main"><div class="weather-place"><span class="weather-pin">⌖</span><span><strong>Morrowfield</strong><small>The Orchard Belt</small></span></div><section class="weather-current"><div class="weather-current-copy"><span class="weather-date"></span><h1 class="weather-condition"></h1><div class="weather-temperature"><strong></strong><span>°</span></div><div class="weather-highlow"></div></div><div class="weather-sky-icon" aria-hidden="true"></div></section><section class="weather-metrics"><div><span>HUMIDITY</span><strong class="weather-humidity"></strong></div><div><span>WIND</span><strong class="weather-wind"></strong></div><div><span>PRESSURE</span><strong class="weather-pressure"></strong></div></section><section class="weather-outlook"><div class="weather-outlook-heading"><span>THE NEXT FEW DAYS</span><small>simulated outlook</small></div><div class="weather-days"></div></section><p class="weather-footnote">A tiny world, generated by a local weather algorithm. Not real-world weather.</p></main></div>';

    const now = new Date();
    const utcDay = Math.floor(Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86400000);
    const random = seededRandom(utcDay + 20873);
    const dayOfYear = Math.floor((Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) - Date.UTC(now.getFullYear(), 0, 0)) / 86400000);
    const seasonalBase = 15 + 9 * Math.sin((2 * Math.PI * (dayOfYear - 82)) / 365.25);
    const conditions = [
        { name: 'Clear skies', icon: '☀️', effect: 2 },
        { name: 'Sun & clouds', icon: '🌤️', effect: 1 },
        { name: 'Cloudy', icon: '☁️', effect: -1 },
        { name: 'Light rain', icon: '🌦️', effect: -3 },
        { name: 'Rain showers', icon: '🌧️', effect: -4 },
        { name: 'Breezy', icon: '🌬️', effect: -1 }
    ];
    const forecast = [];
    let moisture = 0.25 + random() * 0.5;
    let pressure = 1014 + (random() - 0.5) * 20;
    for (let day = 0; day < 6; day++) {
        moisture = clamp(moisture * 0.67 + random() * 0.38, 0.08, 0.96);
        pressure = clamp(pressure * 0.72 + (1008 + random() * 20) * 0.28, 986, 1032);
        let conditionIndex;
        if (moisture > 0.79) conditionIndex = random() > 0.45 ? 4 : 3;
        else if (moisture > 0.62) conditionIndex = random() > 0.55 ? 3 : 2;
        else if (moisture > 0.47) conditionIndex = random() > 0.45 ? 2 : 1;
        else conditionIndex = random() > 0.2 ? 0 : 5;
        const condition = conditions[conditionIndex];
        const daySwing = (random() - 0.5) * 8;
        const high = Math.round(seasonalBase + condition.effect + daySwing + 4);
        const low = Math.round(high - 5 - random() * 5);
        forecast.push({ condition, high, low, humidity: Math.round(36 + moisture * 57), wind: Math.round(5 + random() * 29), pressure: Math.round(pressure) });
    }

    const current = forecast[0];
    const solar = clamp(Math.sin(((now.getHours() - 6) / 12) * Math.PI), 0, 1);
    const temperature = Math.round(current.low + (current.high - current.low) * solar);
    root.querySelector('.weather-date').textContent = now.toLocaleDateString([], { weekday: 'long', month: 'long', day: 'numeric' });
    root.querySelector('.weather-condition').textContent = current.condition.name;
    root.querySelector('.weather-temperature strong').textContent = String(temperature);
    root.querySelector('.weather-highlow').textContent = 'H ' + current.high + '°   ·   L ' + current.low + '°';
    root.querySelector('.weather-sky-icon').textContent = current.condition.icon;
    root.querySelector('.weather-humidity').textContent = current.humidity + '%';
    root.querySelector('.weather-wind').textContent = current.wind + ' km/h';
    root.querySelector('.weather-pressure').textContent = current.pressure + ' hPa';

    const dayLabels = ['Today', ...Array.from({ length: 5 }, (_, index) => {
        const date = new Date(now.getFullYear(), now.getMonth(), now.getDate() + index + 1);
        return date.toLocaleDateString([], { weekday: 'short' });
    })];
    const days = root.querySelector('.weather-days');
    forecast.forEach((day, index) => {
        const item = document.createElement('div'); item.className = 'weather-day';
        const name = document.createElement('span'); name.className = 'weather-day-name'; name.textContent = dayLabels[index];
        const icon = document.createElement('span'); icon.className = 'weather-day-icon'; icon.textContent = day.condition.icon;
        const temp = document.createElement('strong'); temp.textContent = day.high + '°';
        const low = document.createElement('small'); low.textContent = day.low + '°';
        item.append(name, icon, temp, low); days.appendChild(item);
    });
    return root;
}
